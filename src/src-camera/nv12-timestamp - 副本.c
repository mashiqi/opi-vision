#define CHAR_W     8
#define CHAR_H    16
#define OUTLINE_W 10
#define OUTLINE_H 18

/*
 * 在输出空间中绘制一个字符（白字 + 黑描边）。
 * (char_ox, char_oy) = 字符左上角在最终输出画面中的坐标。
 * rotate = 编码器将应用的顺时针旋转角度。
 * 本函数通过逆旋转映射找到对应输入帧中的像素位置并写入。
 */
static void draw_char_output_space(
    unsigned char *frame,
    int W_in, int H_in,
    int char_ox, int char_oy,
    unsigned char ch,
    int rotate)
{
    int row, col;

    /* ── 第一趟：描边（深色 Y=32） ──────────────────── */
    {
        const uint16_t *ol_rows = font_outline[ch];
        for (row = 0; row < OUTLINE_H; row++) {
            uint16_t ol_row = ol_rows[row];
            for (col = 0; col < OUTLINE_W; col++) {
                if (!(ol_row & (1u << (9 - col))))
                    continue;

                int ox = char_ox + col - 1;
                int oy = char_oy + row - 1;
                int ix, iy;

                switch (rotate) {
                case 0:   ix = ox;                     iy = oy;                        break;
                case 90:  ix = oy;                     iy = H_in - 1 - ox;             break;
                case 180: ix = W_in - 1 - ox;          iy = H_in - 1 - oy;             break;
                case 270: ix = W_in - 1 - oy;          iy = ox;                        break;
                default:  return;
                }

                if (ix < 0 || ix >= W_in || iy < 0 || iy >= H_in)
                    continue;

                frame[iy * W_in + ix] = 32;

                int uv_x    = ix & ~1;
                int uv_y    = iy & ~1;
                int uv_off  = W_in * H_in + (uv_y / 2) * W_in + uv_x;
                frame[uv_off]     = 128;
                frame[uv_off + 1] = 128;
            }
        }
    }

    /* ── 第二趟：字形（亮色 Y=240） ──────────────────── */
    {
        const unsigned char *glyph = font[ch];
        for (row = 0; row < CHAR_H; row++) {
            unsigned char bitmap = glyph[row];
            for (col = 0; col < CHAR_W; col++) {
                if (!(bitmap & (1 << (7 - col))))
                    continue;

                int ox = char_ox + col;
                int oy = char_oy + row;
                int ix, iy;

                switch (rotate) {
                case 0:   ix = ox;                     iy = oy;                        break;
                case 90:  ix = oy;                     iy = H_in - 1 - ox;             break;
                case 180: ix = W_in - 1 - ox;          iy = H_in - 1 - oy;             break;
                case 270: ix = W_in - 1 - oy;          iy = ox;                        break;
                default:  return;
                }

                if (ix < 0 || ix >= W_in || iy < 0 || iy >= H_in)
                    continue;

                frame[iy * W_in + ix] = 240;

                int uv_x    = ix & ~1;
                int uv_y    = iy & ~1;
                int uv_off  = W_in * H_in + (uv_y / 2) * W_in + uv_x;
                frame[uv_off]     = 128;
                frame[uv_off + 1] = 128;
            }
        }
    }
}

static void print_usage(const char *prog)
{
    fprintf(stderr,
        "用法: %s --width <W> --height <H> --rotate <0|90|180|270> [--margin <N>]\n"
        "\n"
        "在 NV12 原始视频帧上叠加系统实时时间戳 (\"YYYY-MM-DD HH:MM:SS\").\n"
        "从 stdin 读取帧, 输出到 stdout.\n"
        "\n"
        "  --width    输入帧宽度 (编码前)\n"
        "  --height   输入帧高度 (编码前)\n"
        "  --rotate   编码器将应用的顺时针旋转角度\n"
        "  --margin   文字距边缘的像素, 默认 8\n",
        prog);
}

int main(int argc, char *argv[])
{
    int W = 0, H = 0, rotate = -1, margin = 8;
    int i;

    for (i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--width") && i + 1 < argc)
            W = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--height") && i + 1 < argc)
            H = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--rotate") && i + 1 < argc)
            rotate = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--margin") && i + 1 < argc)
            margin = atoi(argv[++i]);
        else {
            print_usage(argv[0]);
            return 1;
        }
    }

    if (W <= 0 || H <= 0) {
        fprintf(stderr, "错误: 必须指定有效的 --width 和 --height\n");
        return 1;
    }
    if (rotate != 0 && rotate != 90 && rotate != 180 && rotate != 270) {
        fprintf(stderr, "错误: --rotate 必须是 0, 90, 180 或 270\n");
        return 1;
    }
    if (margin < 0) margin = 0;

    size_t frame_size = (size_t)W * H * 3 / 2;
    unsigned char *frame = (unsigned char *)malloc(frame_size);
    if (!frame) {
        perror("malloc");
        return 1;
    }

    char time_str[32];

    for (;;) {
        size_t total = 0;
        while (total < frame_size) {
            ssize_t n = (ssize_t)READ(STDIN_FILENO, frame + total, frame_size - total);
            if (n <= 0) {
                free(frame);
                return n == 0 ? 0 : 1;
            }
            total += (size_t)n;
        }

        time_t now_ts = time(NULL);
        struct tm tm_now;
        localtime_r(&now_ts, &tm_now);
        strftime(time_str, sizeof(time_str), "%Y-%m-%d %H:%M:%S", &tm_now);

        int text_len = (int)strlen(time_str);
        int char_ox = margin;
        int char_oy = margin;
        int k;
        for (k = 0; k < text_len; k++) {
            draw_char_output_space(frame, W, H,
                char_ox + k * CHAR_W, char_oy,
                (unsigned char)time_str[k],
                rotate);
        }

        total = 0;
        while (total < frame_size) {
            ssize_t n = (ssize_t)WRITE(STDOUT_FILENO, frame + total, frame_size - total);
            if (n <= 0) {
                free(frame);
                return n == 0 ? 0 : 1;
            }
            total += (size_t)n;
        }
    }
}
